-- Student coursework mapping is deliberately separate from Admin corrections.
-- Raw submission evidence and the canonical correction audit remain immutable;
-- this table records student suggestions and trainer review decisions.

-- Trainer roster commits share the existing import audit table. The historical
-- constraint was admin-only, so widen only that audit-role check for this
-- feature; authorization remains enforced by the custom trainer scope.
alter table public.student_roster_imports
  drop constraint if exists student_roster_import_role_check;
alter table public.student_roster_imports
  add constraint student_roster_import_role_check
  check (uploaded_by_role in ('admin', 'teacher'));

create table if not exists public.coursework_mapping_requests (
  id bigint generated by default as identity primary key,
  submission_id text not null,
  student_id uuid not null references public.students(id) on delete cascade,
  batch text not null,
  source_topic text not null,
  source_item_type text,
  source_phase text,
  target_coursework_item_id uuid references public.coursework_items(id) on delete restrict,
  target_title text,
  target_item_type text,
  status text not null default 'pending_review' check (status in ('pending_review', 'auto_applied', 'approved', 'rejected')),
  reason text,
  requested_by_role text not null check (requested_by_role in ('student', 'teacher', 'admin', 'system')),
  requested_by_name text not null,
  reviewed_by_role text,
  reviewed_by_name text,
  reviewed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists coursework_mapping_requests_student_status_idx
  on public.coursework_mapping_requests (student_id, status, created_at desc);
create index if not exists coursework_mapping_requests_batch_status_idx
  on public.coursework_mapping_requests (batch, status, created_at desc);
create index if not exists coursework_mapping_requests_submission_status_idx
  on public.coursework_mapping_requests (submission_id, status, created_at desc);
create unique index if not exists coursework_mapping_requests_pending_submission_idx
  on public.coursework_mapping_requests (submission_id)
  where status = 'pending_review';

create table if not exists public.coursework_mapping_request_events (
  id bigint generated by default as identity primary key,
  request_id bigint not null references public.coursework_mapping_requests(id) on delete cascade,
  from_status text,
  to_status text not null,
  actor_role text not null check (actor_role in ('student', 'teacher', 'admin', 'system')),
  actor_name text not null,
  reason text,
  created_at timestamptz not null default now()
);

create index if not exists coursework_mapping_request_events_request_idx
  on public.coursework_mapping_request_events (request_id, created_at desc);

create or replace function public.cf_touch_coursework_mapping_request()
returns trigger
language plpgsql
security invoker
set search_path = public
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists coursework_mapping_requests_touch on public.coursework_mapping_requests;
create trigger coursework_mapping_requests_touch
before update on public.coursework_mapping_requests
for each row execute function public.cf_touch_coursework_mapping_request();

alter table public.coursework_mapping_requests enable row level security;
alter table public.coursework_mapping_request_events enable row level security;
drop policy if exists coursework_mapping_requests_deny_public on public.coursework_mapping_requests;
create policy coursework_mapping_requests_deny_public
  on public.coursework_mapping_requests for all to anon, authenticated
  using (false) with check (false);
drop policy if exists coursework_mapping_request_events_deny_public on public.coursework_mapping_request_events;
create policy coursework_mapping_request_events_deny_public
  on public.coursework_mapping_request_events for all to anon, authenticated
  using (false) with check (false);
revoke all on public.coursework_mapping_requests from anon, authenticated;
revoke all on public.coursework_mapping_request_events from anon, authenticated;
grant all on public.coursework_mapping_requests to service_role;
grant all on public.coursework_mapping_request_events to service_role;
grant usage, select on all sequences in schema public to service_role;

